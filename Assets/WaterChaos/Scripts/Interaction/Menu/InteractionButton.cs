namespace WaterChaos.Interaction
{
    /// <summary>Button that performs an action directly, without opening the menu.</summary>
    public enum InteractionButton
    {
        /// <summary>Primary button (left mouse button).</summary>
        Primary,

        /// <summary>Interact key (E): performs the action instead of opening the menu, e.g. Pick Up.</summary>
        Interact,
    }
}
